"""Generate docs/RESULTS.md from out/canon.json.

The repository used to carry five hand-written per-stage result documents. Every one of them
drifted: they quoted an epoch rule that was replaced, a lower bound of 12/12 that is now 11/12,
correlations from before the epoch fix, follow rates from the selected-layer estimator, a path
(analysis/tables/) that no longer exists, and in one case a thesis -- that the diagnostic predicts
fine-tuning gain -- that the analysis now withdraws. Hand-maintained numbers beside generated
ones is the same defect run/manifest.py exists to prevent one level down, so the results document
is generated too.

    python3 run/canon.py && python3 run/results_md.py     # -> docs/RESULTS.md

Every figure below is read from out/canon.json. Nothing here is typed by hand.
"""
from __future__ import annotations
import json, os, sys

from scipy.stats import binomtest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
# imported rather than repeated: this document states which statistic the gate is applied to, and
# a second copy of that name is how the document came to describe a rule canon.py had stopped
# running. canon.py guards its entry point, so importing it runs nothing.
from canon import GATE_CI

JSON = os.environ.get("VLM_LOCUS_JSON", "out/canon.json")
OUT = os.environ.get("VLM_LOCUS_DOCS", "docs/RESULTS.md")


def pct(x, d=1):
    return "--" if x is None or x != x else f"{100 * x:.{d}f}"


def sgn(x, d=1):
    return "--" if x is None or x != x else f"{x:+.{d}f}"


def cell_table(rows, C):
    out = ["| model | family | n | chance | model | probe | gap | null q95 | "
           "p(null) | McNemar | follow | joint | bound | locus |",
           "|---|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|"]
    for r in rows:
        nc, pq = r["nullcal"], r.get("paired")
        out.append(
            f"| {r['label']} | {r['family']} | {r['n_test']} | {pct(r['chance'])} | "
            f"{pct(r['model_acc'])} | {pct(r['probe'])} | {sgn(r['gap'])} | "
            f"{pct(nc['null_q95'])} | {nc['p_null']:.4f} | "
            f"{(f'{pq[chr(112)]:.2g}' if pq else '--')} | "
            f"{r['probe_follow_num']}/{r['probe_follow_den']} | "
            f"{r['probe_joint_num']}/{r['probe_joint_den']} | "
            f"{pct(r[GATE_CI][0], 0)} | "
            f"{'**readout**' if r['readout'] else '--'} |")
    return "\n".join(out)


def main():
    C = json.load(open(JSON))
    rows = C["synthetic"] + C["real"]
    loci = [r for r in rows if r["readout"]]
    clears = [r for r in rows if r["nullcal"]["p_null"] < C["protocol"]["null_alpha"]]
    gl = [r for r in C["real"] if r["family"].startswith("glyph")]
    cn = [r for r in rows if r["family"] == "counting"]
    fs, mu = C["follow_sensitivity"], C["multiplicity"]
    pr = C["prediction"]["stats"]
    q95 = [100 * r["nullcal"]["null_q95"] for r in rows]

    L = []
    w = L.append
    w("<!-- generated by run/results_md.py from out/canon.json -- do not edit -->")
    w("# Results\n")
    w(f"Generated from `{JSON}` by `run/results_md.py`. Regenerate with "
      "`python3 run/canon.py && python3 run/results_md.py`. Every number on this page is read "
      "from that file; none is typed in, and the output is byte-stable for a given input --- so "
      "regenerating and diffing is itself a check that the document matches the artefacts.\n")

    w("## The verdict\n")
    w(f"A **readout locus** is a (model, family) cell where the queried attribute is linearly "
      f"decodable from the final hidden state well above what the model emits, and the decoding "
      f"is shown to track the attribute rather than a correlate. A cell qualifies only if all "
      f"four hold:\n")
    w("1. it passes the presence test at the final layer -- beating a blindfolded refit and its "
      "own shuffled-label control on accuracy and on per-item log-probability margin;")
    w("2. it rejects **its own** label-permutation null "
      f"(`p < {C['protocol']['null_alpha']}`, add-one corrected);")
    w("3. it beats the model on the same items under an exact paired test (`p < 0.05`);")
    w(f"4. the **lower 95% bound** on its joint two-endpoint accuracy exceeds "
      f"{C['protocol']['follow_min_pct']:.0f}%.\n")
    byfam = {}
    for r in loci: byfam[r["family"]] = byfam.get(r["family"], 0) + 1
    w(f"Of {len(rows)} cells, {len(clears)} clear their own null and **{len(loci)} are readout "
      f"loci**, in {len(byfam)} of the {len({r['family'] for r in rows})} families measured: "
      + ", ".join(f"{k} ({v})" for k, v in sorted(byfam.items())) + ".\n")

    w("| | count |")
    w("|---|--:|")
    w(f"| cells measured | {len(rows)} |")
    w(f"| clear their own permutation null | {len(clears)} |")
    w(f"| readout loci | {len(loci)} |")
    w(f"| rejected on the counterfactual alone | "
      f"{sum(1 for r in clears if not r['readout'] and r['paired']['p'] < 0.05 and r['gap'] > 0)} |")
    w("")

    w("## Why the threshold cannot be a constant\n")
    w(f"The null's 95th percentile runs from **{min(q95):.1f}% to {max(q95):.1f}%** across the "
      f"grid as the class count and sample size vary, so no single percentage-point floor serves: "
      f"it is simultaneously too strict on the low-class families and too permissive on the "
      f"high-class ones. This is the reason the protocol calibrates per cell rather than applying "
      f"one measured floor.\n")

    w("## The designed absence\n")
    w(f"The `glyph` family renders a numeral below the resolution at which any model reads it, so "
      f"there should be nothing to decode. Across {len(gl)} configurations the presence test "
      f"fires in **{sum(1 for r in gl if r['nullcal']['p_null'] < 0.05)}**, and the composed "
      f"locus verdict in **{sum(1 for r in gl if r['readout'])}**.\n")
    w("| config | probe | null q95 | p(null) | follow | presence | locus |")
    w("|---|--:|--:|--:|--:|:--|:--|")
    for r in gl:
        w(f"| {r['label']} | {pct(r['probe'])} | {pct(r['nullcal']['null_q95'])} | "
          f"{r['nullcal']['p_null']:.4f} | {r['probe_follow_num']}/{r['probe_follow_den']} | "
          f"{'fires' if r['nullcal']['p_null'] < 0.05 else '--'} | "
          f"{'**readout**' if r['readout'] else '--'} |")
    w("")
    k = sum(1 for r in gl if r["nullcal"]["p_null"] < 0.05)
    bt = binomtest(k, len(gl), C["protocol"]["null_alpha"])
    ci = bt.proportion_ci(0.95)
    w(f"That {k}-of-{len(gl)} needs its arithmetic stated rather than a label attached to it. A "
      f"correctly calibrated test at alpha = {C['protocol']['null_alpha']} *expects* "
      f"{len(gl) * C['protocol']['null_alpha']:.2f} false positives in {len(gl)} cells and "
      f"produces at least one about {bt.pvalue:.0%} of the time, so {k} is what a nominal test "
      f"looks like, not evidence against it (exact binomial against alpha, p = {bt.pvalue:.3f}). "
      f"Equally, {len(gl)} cells cannot resolve the rate: the 95% interval on {k}/{len(gl)} runs "
      f"from {100 * ci.low:.1f}% to {100 * ci.high:.0f}%. What the family establishes is therefore "
      f"weaker than a measured false-positive rate and stronger than nothing --- the null is not "
      f"*grossly* miscalibrated on a family designed to have nothing to read, and the one cell "
      f"that fires is identified rather than absorbed into a constant floor. Resolving the rate "
      f"needs a designed absence an order of magnitude larger, which this study does not have.\n")

    w("## Counting: the protocol's cleanest negative\n")
    w(f"All **{sum(1 for r in cn if r['nullcal']['p_null'] < 0.05)} of {len(cn)}** counting cells "
      f"decode above their own null, and **{sum(1 for r in cn if r['readout'])}** survive the "
      f"counterfactual. Follow rates run "
      f"{pct(min(r['follow'] for r in cn), 0)}--{pct(max(r['follow'] for r in cn), 0)}%. The "
      f"information is there; the probe is reading a correlate of the count rather than the "
      f"count, and no accuracy comparison at any layer would have shown it.\n")

    sh = C.get("sham") or []
    if sh:
        w("## The label-preserving control\n")
        w("Every other counterfactual here changes the answer, so following one shows the probe "
          "responds to *something* the edit did -- not that it responds to the attribute rather "
          "than to a cue travelling with it. The sham edit changes the image and not the answer: "
          "it applies each family's own primitive where the question is not looking, at a size "
          "that is not smaller than the real edit. A reader of the attribute must return the "
          "same answer; a reader of the scene may not.\n")
        w("| config | family | n | follows real | probe moved | model moved | locus |")
        w("|---|---|--:|--:|--:|--:|:--|")
        for b in sorted(sh, key=lambda b: (b["family"] != "chart", b["family"], b["label"])):
            fr = ("--" if not b.get("follow_den")
                  else f"{b['follow_num']}/{b['follow_den']}")
            w(f"| {b['label']} | {b['family']} | {b['n']} | {fr} | "
              f"{b['probe_moved']} | {b['model_moved']} | "
              f"{'**readout**' if b['readout'] else '--'} |")
        w("")
        lo = [b for b in sh if b["cf_pass"]]
        hi = [b for b in sh if not b["cf_pass"]]
        if lo and hi:
            a = max(b["probe_moved"] / b["n"] for b in lo)
            c = min(b["probe_moved"] / b["n"] for b in hi)
            w(f"The two halves separate, and they separate completely. Every one of the "
              f"{len(lo)} cells that passes the counterfactual condition moves on at most "
              f"{100*a:.1f}% of its items; every one of the {len(hi)} that fails it moves on at "
              f"least {100*c:.1f}%. Nothing here is thresholded -- that is a max against a min, "
              f"and no constant was chosen to produce it.\n")
            w("The grouping is on the counterfactual condition rather than on the locus verdict, "
              "and the difference matters. Both statistics are counterfactual; the verdict also "
              "prices the model, so the one chart cell that reads its attribute perfectly and is "
              "not a locus -- because the model reads it too -- belongs with the passing group "
              "here. Grouping on the verdict would place it, at 0 of 114 moved, among the "
              "failures and erase the separation.\n")
            w("Neither rate means anything alone: a probe that never moves has shown nothing if "
              "it also never follows. Both are reported on the same items and the same probe.\n")

    w("## Sensitivity of the one prespecified threshold\n")
    w(f"The follow threshold is the only free constant in the protocol. Applied to the lower "
      f"bound, the verdict set is unchanged for every threshold in "
      f"**[{fs['lo']}, {fs['hi']}]**. Outside that range it changes one cell at a time: above "
      f"{fs['hi']}, `{', '.join(fs['dropped_above']) or 'none'}` falls first; below {fs['lo']}, "
      f"`{', '.join(fs['admitted_below']) or 'none'}` is admitted. The range does not reach zero, "
      f"so \"any low threshold would do\" is not available as a defence.\n")

    w("## Multiplicity\n")
    w(f"The permutation `p` is at its floor for every locus, so the binding quantity is the "
      f"paired test; it is corrected across all {mu['n']} cells at once. Under "
      f"Benjamini--Hochberg **{len(mu['loci_bh'])}/{len(mu['loci'])}** loci survive; under Holm, "
      f"**{len(mu['loci_holm'])}/{len(mu['loci'])}**"
      + (f", the exception being `{', '.join(mu['loci_holm_fail'])}`" if mu["loci_holm_fail"] else "")
      + ".\n")

    w("## What the diagnostic does not buy\n")
    pg = pr["probe_gain"]
    w(f"Probe gain is associated with fine-tuning gain in sample --- family-demeaned "
      f"Spearman rho = {pg['rho_dm']:+.3f} (p = {pg['p_dm']:.4f}), incremental "
      f"F(1,{pr['oos']['insample']['df'][1]}) = {pr['oos']['insample']['F']:.2f} "
      f"(p = {pr['oos']['insample']['p']:.3f}), and p = {pr['coupling_null']['p']:.4f} against a "
      f"permutation null that keeps the shared-baseline coupling intact. Out of sample it buys "
      f"nothing detectable:\n")
    w("| held out | MAE baseline | MAE with probe | difference | paired p | 95% CI |")
    w("|---|--:|--:|--:|--:|--:|")
    for k in ("model", "family"):
        o = pr["oos"][f"heldout_{k}"]
        w(f"| one {k} at a time | {o['mae_baseline']:.2f} | {o['mae_with_probe']:.2f} | "
          f"{o['delta']:+.2f} | {o['p_paired']:.2f} | "
          f"[{o['ci'][0]:+.1f}, {o['ci'][1]:+.1f}] |")
    w("")
    w("Neither difference is resolved and the per-fold directions disagree, so this is a report "
      "of **no demonstrable benefit**, not of harm. An instrument earns its use by demonstrating "
      "benefit; on the evidence here this one does not, and should not be used to triage which "
      "fine-tuning run to launch.\n")
    w("Per-fold difference in MAE (pp, positive = worse with the probe):\n")
    for k in ("model", "family"):
        f_ = pr["oos"][f"heldout_{k}"]["per_fold"]
        w(f"- held out one {k}: " + ", ".join(f"`{g}` {v:+.2f}" for g, v in sorted(f_.items())))
    w("")

    w("## All cells\n")
    w("`follow` is numerator/denominator among items the probe answered correctly *before* the "
      "edit -- a conditional statistic, and one the probe's class support truncates, so it is "
      "reported but not gated on. `joint` is the share of all n items read correctly at both "
      "endpoints of the edit, and `bound` is its lower 95% Wilson bound, which is what the gate "
      "is applied to.\n")
    w("### Synthetic families\n")
    w(cell_table(C["synthetic"], C) + "\n")
    w("### Real-image families\n")
    w(cell_table(C["real"], C) + "\n")

    os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT}  ({len(L)} blocks, {len(rows)} cells, {len(loci)} loci)")


if __name__ == "__main__":
    sys.exit(main())
